package com.attentive.screens.processor

internal object ScreenCatalogRenderer {
    fun render(catalog: ScreenCatalog): String =
        buildString {
            val visibility = if (catalog.isInternal) "internal" else "public"

            appendLine("// Generated by attentive-screens-processor from ${catalog.sourceName}. Do not edit.")
            if (catalog.packageName.isNotEmpty()) {
                appendLine("package ${catalog.packageName}")
                appendLine()
            }
            appendLine("import com.attentive.androidsdk.screens.AttentiveScreenCatalog")
            appendLine()
            appendLine("$visibility object ${catalog.objectName} : AttentiveScreenCatalog {")
            for (screen in catalog.screens) {
                appendLine("    $visibility const val ${screen.constantName}: String = \"${screen.screenName}\"")
            }
            if (catalog.screens.isNotEmpty()) appendLine()

            appendLine("    override val names: Map<String, String> =")
            appendLine("        mapOf<String, String>(")
            for (screen in catalog.screens) {
                appendLine("            ${screen.keyExpression} to ${screen.constantName},")
            }
            appendLine("        )")
            appendLine()
            appendLine("    override val ignored: Set<String> =")
            appendLine("        setOf<String>(")
            for (key in catalog.ignoredKeyExpressions) {
                appendLine("            $key,")
            }
            appendLine("        )")
            appendLine("}")
        }

    /** A Kotlin string literal for [value]. */
    fun stringLiteral(value: String): String = "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
}
