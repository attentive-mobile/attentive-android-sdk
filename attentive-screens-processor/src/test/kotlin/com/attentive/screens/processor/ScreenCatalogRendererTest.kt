package com.attentive.screens.processor

import org.junit.Assert.assertEquals
import org.junit.Test

class ScreenCatalogRendererTest {
    @Test
    fun render_writesCatalogObject() {
        val catalog =
            ScreenCatalog(
                packageName = "com.example",
                objectName = "RoutesScreens",
                sourceName = "Routes",
                isInternal = false,
                screens =
                    listOf(
                        CatalogScreen("WELCOME", "welcome", "com.example.Routes.WelcomeScreenRoute.name"),
                        CatalogScreen("PDP", "pdp", "com.example.Routes.ProductScreenRoute.name"),
                    ),
                ignoredKeyExpressions = listOf("com.example.Routes.SplashScreen.name"),
            )

        assertEquals(
            """
            // Generated by attentive-screens-processor from Routes. Do not edit.
            package com.example

            import androidx.navigation.NavController
            import com.attentive.androidsdk.screens.AttentiveScreenCatalog
            import com.attentive.androidsdk.screens.AttentiveScreenTracking

            public object RoutesScreens : AttentiveScreenCatalog {
                public const val WELCOME: String = "welcome"
                public const val PDP: String = "pdp"

                override val names: Map<String, String> =
                    mapOf<String, String>(
                        com.example.Routes.WelcomeScreenRoute.name to WELCOME,
                        com.example.Routes.ProductScreenRoute.name to PDP,
                    )

                override val ignored: Set<String> =
                    setOf<String>(
                        com.example.Routes.SplashScreen.name,
                    )

                /** Starts tracking screens for [navController] with this catalog. Close the returned handle to stop. */
                @JvmStatic
                public fun track(navController: NavController): AutoCloseable =
                    AttentiveScreenTracking.trackNavigation(navController, this)
            }

            """.trimIndent(),
            ScreenCatalogRenderer.render(catalog),
        )
    }

    @Test
    fun render_internalCatalogInRootPackage() {
        val catalog =
            ScreenCatalog(
                packageName = "",
                objectName = "RouteScreens",
                sourceName = "Route",
                isInternal = true,
                screens = listOf(CatalogScreen("HOME", "home", "\"Route.Home\"")),
                ignoredKeyExpressions = emptyList(),
            )

        assertEquals(
            """
            // Generated by attentive-screens-processor from Route. Do not edit.
            import androidx.navigation.NavController
            import com.attentive.androidsdk.screens.AttentiveScreenCatalog
            import com.attentive.androidsdk.screens.AttentiveScreenTracking

            internal object RouteScreens : AttentiveScreenCatalog {
                internal const val HOME: String = "home"

                override val names: Map<String, String> =
                    mapOf<String, String>(
                        "Route.Home" to HOME,
                    )

                override val ignored: Set<String> =
                    setOf<String>(
                    )

                /** Starts tracking screens for [navController] with this catalog. Close the returned handle to stop. */
                @JvmStatic
                internal fun track(navController: NavController): AutoCloseable =
                    AttentiveScreenTracking.trackNavigation(navController, this)
            }

            """.trimIndent(),
            ScreenCatalogRenderer.render(catalog),
        )
    }

    @Test
    fun render_composeTracking_addsTrackComposable() {
        val catalog =
            ScreenCatalog(
                packageName = "com.example",
                objectName = "RoutesScreens",
                sourceName = "Routes",
                isInternal = false,
                screens = listOf(CatalogScreen("CART", "cart", "com.example.Routes.CartScreen.name")),
                ignoredKeyExpressions = emptyList(),
                composeTracking = true,
            )

        assertEquals(
            """
            // Generated by attentive-screens-processor from Routes. Do not edit.
            package com.example

            import androidx.compose.runtime.Composable
            import androidx.navigation.NavController
            import com.attentive.androidsdk.screens.AttentiveScreenCatalog
            import com.attentive.androidsdk.screens.AttentiveScreenTracking
            import com.attentive.androidsdk.screens.TrackAttentiveScreens

            public object RoutesScreens : AttentiveScreenCatalog {
                public const val CART: String = "cart"

                override val names: Map<String, String> =
                    mapOf<String, String>(
                        com.example.Routes.CartScreen.name to CART,
                    )

                override val ignored: Set<String> =
                    setOf<String>(
                    )

                /** Starts tracking screens for [navController] with this catalog. Close the returned handle to stop. */
                @JvmStatic
                public fun track(navController: NavController): AutoCloseable =
                    AttentiveScreenTracking.trackNavigation(navController, this)

                /** Tracks screens for [navController] with this catalog while in composition. */
                @Composable
                public fun Track(navController: NavController) {
                    TrackAttentiveScreens(navController, this)
                }
            }

            """.trimIndent(),
            ScreenCatalogRenderer.render(catalog),
        )
    }

    @Test
    fun stringLiteral_escapesSpecialCharacters() {
        assertEquals("\"a\\\"b\\\\c\\\$d\"", ScreenCatalogRenderer.stringLiteral("a\"b\\c\$d"))
    }
}
